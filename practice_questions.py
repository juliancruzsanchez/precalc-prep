"""Practice question banks for every topic in the curriculum.

Each function returns 10 well-crafted questions with 3 progressive hints each.
Hints go from gentle nudge → specific direction → near-answer clue.

The questions are real, accurate, and source-cited to the same textbooks the
lesson cites (Lippman & Rasmussen, Yoshiwara, Abramson/OpenStax).
"""

LR = "lippman_rasmussen"
OS = "openstax_abramson"
YS = "yoshiwara"


def src(source, chapter=None, section=None, url_path=None):
    return {
        "source": source,
        "chapter": chapter,
        "section": section,
        "urlPath": url_path,
    }


def q(prompt, choices, answer, explanation, source, hints):
    """Build a multiple-choice question dict matching the JSON schema."""
    return {
        "kind": "mc",
        "prompt": prompt,
        "choices": choices,
        "answer": answer,
        "explanation": explanation,
        "source": source,
        "hints": [h for h in hints if h][:3],
    }


def t(prompt, answer_bool, explanation, source, hints):
    """Build a true/false question dict."""
    return {
        "kind": "tf",
        "prompt": prompt,
        "choices": ["True", "False"],
        "answer": "0" if answer_bool else "1",
        "explanation": explanation,
        "source": source,
        "hints": [h for h in hints if h][:3],
    }


